import { BrandCodeset, IrCommandDef, IrProtocol, RemoteKey, TvBrand } from '../../types/ir';

function makeNecCommands(
  codes: Record<RemoteKey, number>,
  protocol: IrProtocol = 'NEC'
): Record<RemoteKey, IrCommandDef> {
  const entries = Object.entries(codes).map(([key, code]) => [
    key,
    { protocol, code } satisfies IrCommandDef,
  ]);
  return Object.fromEntries(entries) as Record<RemoteKey, IrCommandDef>;
}

