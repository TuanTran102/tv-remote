export function getCodesetsByBrand(brand: TvBrand): BrandCodeset[] {
  return BUNDLED_CODESETS.filter((item) => item.brand === brand).sort(
    (a, b) => a.priority - b.priority
  );
}

export function getCodesetById(codesetId: string): BrandCodeset | undefined {
  return BUNDLED_CODESETS.find((item) => item.id === codesetId);
}
